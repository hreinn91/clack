import { readdir, readFile } from 'node:fs/promises';
import { homedir } from 'node:os';
import { join } from 'node:path';
import type { SessionMessage } from '@anthropic-ai/claude-agent-sdk';
import type { EffortLevel, Item, Stamp } from '../../../../shared/protocol.ts';

/** A content block as it appears in Anthropic API messages. */
export type Block = { type: string; [key: string]: unknown };

const MAX_RESULT_CHARS = 30_000;
const TOOL_BLOCKS = new Set(['tool_use', 'server_tool_use', 'mcp_tool_use']);

export function isToolBlock(block: Block): boolean {
  return TOOL_BLOCKS.has(block.type);
}

export function blocksOf(content: unknown): Block[] {
  if (typeof content === 'string') return [{ type: 'text', text: content }];
  if (Array.isArray(content)) return content.filter((b): b is Block => !!b && typeof b === 'object' && 'type' in b);
  return [];
}

export function toolResultText(content: unknown): string {
  const text = blocksOf(content)
    .map((b) => {
      if (b.type === 'text') return String(b.text ?? '');
      if (b.type === 'image') return '[image]';
      return `[${b.type}]`;
    })
    .join('\n');
  if (text.length <= MAX_RESULT_CHARS) return text;
  return `${text.slice(0, MAX_RESULT_CHARS)}\n… (${text.length - MAX_RESULT_CHARS} more characters not shown)`;
}

// Transcripts store harness bookkeeping as user-role text. None of it was
// typed by the person, so it is left out of the rendered conversation.
const HARNESS_TEXT = /^<(command-name|command-message|command-args|local-command-|task-notification|bash-input|bash-stdout|bash-stderr|user-memory-input)/;

export function cleanUserText(raw: string): string | null {
  const text = raw.replace(/<system-reminder>[\s\S]*?<\/system-reminder>/g, '').trim();
  if (!text || HARNESS_TEXT.test(text)) return null;
  if (text.startsWith('Caveat: The messages below were generated by the user while running local commands')) return null;
  return text;
}

/** Turns the blocks of one assistant message into transcript items. */
export function assistantItems(uuid: string, content: unknown, parent: string | null, stamp: Stamp = {}): Item[] {
  const items: Item[] = [];
  blocksOf(content).forEach((block, i) => {
    const id = `${uuid}:${i}`;
    const sub = parent ? { ...stamp, parent } : stamp;
    if (block.type === 'text' && typeof block.text === 'string' && block.text.trim()) {
      items.push({ kind: 'text', id, text: block.text, ...sub });
    } else if (block.type === 'thinking' && typeof block.thinking === 'string' && block.thinking.trim()) {
      items.push({ kind: 'thinking', id, text: block.thinking, ...sub });
    } else if (isToolBlock(block)) {
      items.push({ kind: 'tool', id: String(block.id), name: String(block.name), input: block.input, ...sub });
    }
  });
  return items;
}

const EFFORTS = new Set(['low', 'medium', 'high', 'xhigh', 'max']);

/** The model named on a reply, unless it is a placeholder such as "<synthetic>". */
export function modelOf(message: unknown): string | undefined {
  const model = (message as { model?: unknown } | null)?.model;
  return typeof model === 'string' && model && !model.startsWith('<') ? model : undefined;
}

/**
 * The effort each reply ran at, keyed by message uuid. Claude Code writes it
 * on every reply in the session's transcript file but the SDK does not pass
 * it on, so the file is read directly. Anything unexpected yields an empty
 * map, which only means the replies are shown without an effort.
 */
export async function readEfforts(sessionId: string): Promise<Map<string, EffortLevel>> {
  const efforts = new Map<string, EffortLevel>();
  try {
    const root = join(process.env.CLAUDE_CONFIG_DIR || join(homedir(), '.claude'), 'projects');
    let raw: string | undefined;
    for (const dir of await readdir(root)) {
      raw = await readFile(join(root, dir, `${sessionId}.jsonl`), 'utf8').catch(() => undefined);
      if (raw !== undefined) break;
    }
    for (const line of raw?.split('\n') ?? []) {
      if (!line.includes('"effort"')) continue;
      const entry = JSON.parse(line) as { type?: unknown; uuid?: unknown; effort?: unknown };
      if (entry.type !== 'assistant' || typeof entry.uuid !== 'string') continue;
      if (typeof entry.effort === 'string' && EFFORTS.has(entry.effort)) efforts.set(entry.uuid, entry.effort as EffortLevel);
    }
  } catch {
    // Best effort: see above.
  }
  return efforts;
}

/** The note a chat shows when an agent working in the background is done. */
export function agentReport(agentType: string | undefined, status: 'completed' | 'failed' | 'stopped'): string {
  const who = agentType ? `A background agent (${agentType})` : 'A background agent';
  if (status === 'failed') return `${who} failed.`;
  if (status === 'stopped') return `${who} was stopped.`;
  return `${who} finished and reported back to Claude.`;
}

/** Rebuilds a transcript from the messages Claude Code saved on disk. */
export function itemsFromHistory(messages: SessionMessage[], efforts: Map<string, EffortLevel> = new Map()): Item[] {
  const items: Item[] = [];
  const tools = new Map<string, Extract<Item, { kind: 'tool' }>>();

  for (const msg of messages) {
    const content = (msg.message as { content?: unknown } | null)?.content;
    // Present in the saved messages, though the SDK's type does not list it.
    const time = Date.parse(String((msg as { timestamp?: unknown }).timestamp ?? ''));
    const when: Stamp = Number.isNaN(time) ? {} : { ts: time };
    if (msg.type === 'assistant') {
      // A subagent's replies sit under the reply that started it, so only top-level ones are signed.
      const stamp: Stamp = msg.parent_tool_use_id
        ? when
        : { ...when, model: modelOf(msg.message), effort: efforts.get(msg.uuid) };
      for (const item of assistantItems(msg.uuid, content, msg.parent_tool_use_id, stamp)) {
        if (item.kind === 'tool') tools.set(item.id, item);
        items.push(item);
      }
    } else if (msg.type === 'user') {
      // Messages Claude Code adds itself (an agent's report, a finished task, reminders) are saved as
      // the user's, marked like this; they are not something the person wrote.
      const saved = msg as { isMeta?: unknown; origin?: { kind?: unknown; name?: unknown }; promptSource?: unknown };
      const injected = saved.isMeta === true || saved.origin !== undefined || saved.promptSource === 'system';
      if (saved.origin?.kind === 'peer') {
        const name = typeof saved.origin.name === 'string' ? saved.origin.name : undefined;
        items.push({ kind: 'notice', id: msg.uuid, level: 'info', text: agentReport(name, 'completed'), ...when });
      }
      const typed: string[] = [];
      for (const block of blocksOf(content)) {
        if (block.type === 'tool_result') {
          const tool = tools.get(String(block.tool_use_id));
          if (tool) tool.result = { text: toolResultText(block.content), isError: block.is_error === true };
        } else if (block.type === 'text' && typeof block.text === 'string' && !msg.parent_tool_use_id && !injected) {
          const text = cleanUserText(block.text);
          if (text) typed.push(text);
        }
      }
      if (typed.length) items.push({ kind: 'user', id: msg.uuid, text: typed.join('\n\n'), ...when });
    }
  }
  return items;
}
